/**
 * Offline-friendly headless Chromium setup for restricted sandboxes.
 *
 * The normal `npx remotion browser ensure` downloads from remotion.media,
 * which some sandboxes cannot reach. This script instead pulls
 * @sparticuz/chromium from the npm registry (a normal npm dependency host),
 * unpacks its Brotli-compressed payload, and assembles a runnable Chromium
 * 131 tree under .browser/chromium, including:
 *   - the Chromium ELF binary
 *   - the NSS/NSPR shared libs it needs (from the AL2023 bundle)
 *   - SwiftShader software-GL libraries next to the binary (ANGLE/swangle)
 *   - a wrapper that exports LD_LIBRARY_PATH
 *
 * On a normal machine you do not need this script — Remotion downloads its
 * own tested Chrome build. It exists so `npm run render` works where only the
 * npm registry and github.com are reachable.
 *
 * Usage: node scripts/prepare-browser.mjs [--force]
 */
import {
  brotliDecompressSync,
} from "node:zlib";
import {
  chmodSync,
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";

const CHROMIUM_PKG = "@sparticuz/chromium";
const CHROMIUM_VERSION = "131.0.1";

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(here, "..");
const browserDir = join(projectRoot, ".browser", "chromium");
const marker = join(browserDir, "BUILD.txt");
const force = process.argv.includes("--force");

if (existsSync(marker) && !force) {
  console.log(`Browser already assembled at ${browserDir} (use --force to rebuild).`);
  process.exit(0);
}

const work = join(tmpdir(), `nexus-browser-${process.pid}`);
mkdirSync(work, { recursive: true });

try {
  // 1. Download the npm tarball (registry.npmjs.org is an allowed host).
  console.log(`Downloading ${CHROMIUM_PKG}@${CHROMIUM_VERSION} from npm…`);
  execFileSync(
    "npm",
    ["pack", `${CHROMIUM_PKG}@${CHROMIUM_VERSION}`, "--pack-destination", work, "--silent"],
    { stdio: "inherit" }
  );
  const tgz = join(work, `sparticuz-chromium-${CHROMIUM_VERSION}.tgz`);

  // 2. Unpack the tarball.
  execFileSync("tar", ["-xzf", tgz, "-C", work], { stdio: "inherit" });
  const bin = join(work, "package", "bin");

  // 3. Brotli-decompress every .br payload (Node has Brotli built in).
  const brFiles = [
    "chromium.br",
    "al2023.tar.br",
    "swiftshader.tar.br",
    "fonts.tar.br",
  ];
  for (const name of brFiles) {
    const from = join(bin, name);
    const to = from.replace(/\.br$/, "");
    process.stdout.write(`Decompressing ${name}… `);
    writeFileSync(to, brotliDecompressSync(readFileSync(from)));
    console.log("done");
  }

  // 4. Assemble the browser tree.
  rmSync(browserDir, { recursive: true, force: true });
  mkdirSync(browserDir, { recursive: true });

  // 4a. Chromium binary.
  cpSync(join(bin, "chromium"), join(browserDir, "chrome"));
  chmodSync(join(browserDir, "chrome"), 0o755);

  // 4b. NSS/NSPR shared libraries (al2023 bundle contains a lib/ tree).
  execFileSync("tar", ["-xf", join(bin, "al2023.tar"), "-C", browserDir], {
    stdio: "inherit",
  });

  // 4c. SwiftShader software GL — Chromium dlopens these next to its binary.
  const swift = join(work, "swiftshader");
  mkdirSync(swift, { recursive: true });
  execFileSync("tar", ["-xf", join(bin, "swiftshader.tar"), "-C", swift], {
    stdio: "inherit",
  });
  for (const lib of [
    "libEGL.so",
    "libGLESv2.so",
    "libvk_swiftshader.so",
    "libvulkan.so.1",
    "vk_swiftshader_icd.json",
  ]) {
    cpSync(join(swift, lib), join(browserDir, lib));
  }

  // 4d. Bundled fonts + fontconfig config (fallback glyphs).
  execFileSync("tar", ["-xf", join(bin, "fonts.tar"), "-C", browserDir], {
    stdio: "inherit",
  });

  // 5. Wrapper that puts the bundled libs on the loader path.
  const wrapper = join(browserDir, "chrome-wrapper");
  writeFileSync(
    wrapper,
    `#!/bin/sh
# Generated by scripts/prepare-browser.mjs — do not edit.
DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
export LD_LIBRARY_PATH="$DIR/lib:\${LD_LIBRARY_PATH:-}"
# NOTE: do NOT export FONTCONFIG_FILE here — the Lambda-oriented fonts.conf
# shipped in the package points at /var/task and makes Blink reject @font-face
# web fonts outright. The system fontconfig (DejaVu) handles fallback glyphs.
exec "$DIR/chrome" "$@"
`
  );
  chmodSync(wrapper, 0o755);

  writeFileSync(
    marker,
    `${CHROMIUM_PKG}@${CHROMIUM_VERSION} assembled ${new Date().toISOString()}\n`
  );

  // 6. Smoke test.
  const version = execFileSync(wrapper, ["--version"], { encoding: "utf8" }).trim();
  console.log(`\nBrowser ready at ${browserDir}`);
  console.log(`Smoke test: ${version}`);
  console.log(`Remotion will use: ${wrapper}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
