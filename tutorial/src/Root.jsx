// Scene manifest — edit durations here (30 fps => 30 frames per second).
const roleScenes = ROLES.map((role, i) => ({
  id: `Role-${role.key}`,
  component: RoleDetailScene,
  durationInFrames: 210,
  componentProps: { roleIndex: i, sceneIndex: 4 + i },
}));

export const SCENES = [
  { id: "Intro", component: IntroScene, durationInFrames: 150 },
  { id: "About", component: AboutScene, durationInFrames: 210 },
  { id: "Glossary", component: GlossaryScene, durationInFrames: 300 },
  { id: "Roles", component: RolesScene, durationInFrames: 210 },
  ...roleScenes,
  { id: "Dashboard", component: DashboardScene, durationInFrames: 180 },
  { id: "Wizard", component: WizardScene, durationInFrames: 270 },
  { id: "Collaboration", component: CollaborationScene, durationInFrames: 240 },
  { id: "MOA", component: MoaScene, durationInFrames: 210 },
  { id: "Reports", component: ReportScene, durationInFrames: 240 },
  { id: "PublicSite", component: PublicSiteScene, durationInFrames: 210 },
  { id: "Security", component: SecurityScene, durationInFrames: 180 },
  { id: "Outro", component: OutroScene, durationInFrames: 180 },
];

export const TOTAL_DURATION = SCENES.reduce((sum, s) => sum + s.durationInFrames, 0);
export const SCENE_COUNT = SCENES.length;

// Start frame of each scene in the flattened timeline.
const SCENE_STARTS = SCENES.map((_, i) =>
  SCENES.slice(0, i).reduce((sum, s) => sum + s.durationInFrames, 0)
);

// Music ducking: the bed sits low while a voiceover line is expected and
// opens up in the breathing room near each scene boundary. Intervals are
// merged and the resulting keyframes are guaranteed strictly increasing so
// they satisfy interpolate()'s input-range contract.
const OPEN = 0.24;
const DUCKED = 0.09;
const RAMP = 8; // frames over which the level glides between states
const VO_LEAD = 6; // frames after scene start when the line begins
const TAIL = 14; // frames reserved at the end of each scene
const volumeKeyframes = (() => {
  const raw = SCENES.map((scene, i) => [
    Math.max(0, SCENE_STARTS[i] + VO_LEAD - RAMP),
    SCENE_STARTS[i] + scene.durationInFrames - TAIL,
  ])
    // Only duck under scenes that actually have a voiceover clip.
    .filter((_, i) => narrationManifest.scenes.includes(i + 1))
    .sort((a, b) => a[0] - b[0]);

  // Merge overlapping duck intervals.
  const merged = [];
  for (const [a, b] of raw) {
    const last = merged[merged.length - 1];
    if (last && a <= last[1]) last[1] = Math.max(last[1], b);
    else merged.push([a, b]);
  }

  const pairs = [{ f: 0, v: OPEN }];
  const push = (f, v) => {
    const ff = Math.min(Math.max(f, 0), TOTAL_DURATION);
    const prev = pairs[pairs.length - 1];
    if (ff <= prev.f) return; // enforce strict monotonicity
    pairs.push({ f: ff, v });
  };
  for (const [a, b] of merged) {
    push(a, OPEN);
    push(a + RAMP, DUCKED);
    push(b, DUCKED);
    push(b + RAMP, OPEN);
  }
  push(TOTAL_DURATION, OPEN);

  return {
    frames: pairs.map((p) => p.f),
    values: pairs.map((p) => p.v),
  };
})();

const MusicBed = () => (
  <Audio
    src={staticFile("music/nexus-bed.wav")}
    volume={(f) =>
      interpolate(f, volumeKeyframes.frames, volumeKeyframes.values, {
        extrapolateLeft: "clamp",
        extrapolateRight: "clamp",
      })
    }
  />
);

const NexusTutorial = () => (
  <>
    <Fonts />
    <MusicBed />
    {SCENES.map((scene, i) => {
      const from = SCENE_STARTS[i];
      const Scene = scene.component;
      const sceneNo = i + 1;
      const hasNarration = narrationManifest.scenes.includes(sceneNo);
      const narrationFile = `narration/scene-${String(sceneNo).padStart(2, "0")}.mp3`;
      return (
        <Sequence
          key={scene.id}
          from={from}
          durationInFrames={scene.durationInFrames}
          layout="none"
        >
          <Scene {...(scene.componentProps ?? {})} />
          {hasNarration && <Audio src={staticFile(narrationFile)} volume={1} />}
        </Sequence>
      );
    })}
  </>
);

export const RemotionRoot = () => (
  <Composition
    id="NexusTutorial"
    component={NexusTutorial}
    durationInFrames={TOTAL_DURATION}
    fps={VIDEO.fps}
    width={VIDEO.width}
    height={VIDEO.height}
  />
);
